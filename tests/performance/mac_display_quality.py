#!/usr/bin/env python3
"""Offline Mac PNG/H.264 decode + draw comparison; never contacts a device.

H.264 is generated by local FFmpeg/libx264, NOT the deployed Ubuntu OpenH264.
Results describe this fixture and Mac receiver, not end-to-end network FPS.
"""
import argparse
import base64
import json
from pathlib import Path
import re
import shutil
import subprocess

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output', required=True, type=Path)
args = parser.parse_args()
root = Path(__file__).resolve().parents[2]
out = args.output.resolve(); out.mkdir(parents=True, exist_ok=True)
source = root/'apps/mac-windowhost/Sources/PaneFerryWindowHost'
binary = out/'probe'
subprocess.run(['swiftc', '-O', '-module-cache-path', '/tmp/lra-network-verification/swift-cache',
    str(source/'ChromaAtlas.swift'), str(source/'H264Decoder.swift'), str(source/'SurfaceView.swift'), str(source/'RenderGeometry.swift'),
    str(root/'tests/performance/MacDisplayQuality.swift'), '-o', str(binary)], check=True)
subprocess.run([str(binary), 'generate', str(out)], check=True)
ffmpeg = shutil.which('ffmpeg')
assert ffmpeg, 'This optional comparison requires an existing FFmpeg with libx264'
command = [ffmpeg, '-hide_banner', '-loglevel', 'error', '-y', '-framerate', '30', '-i', str(out/'frame-%03d.png'),
    '-frames:v', '60', '-c:v', 'libx264', '-preset', 'veryfast', '-tune', 'zerolatency', '-pix_fmt', 'yuv420p',
    '-b:v', str(1470*802*3), '-maxrate', str(1470*802*6), '-bufsize', str(1470*802*6),
    '-x264-params', 'bframes=0:keyint=60:scenecut=0:aud=1:qpmax=28', '-f', 'h264', str(out/'sample.h264')]
subprocess.run(command, check=True, timeout=90)
video = (out/'sample.h264').read_bytes()
starts = [m.start() for m in re.finditer(rb'\x00\x00\x00?\x01\x09', video)]
assert len(starts) == 60 and starts[0] == 0, starts
packets = [video[start:end] for start, end in zip(starts, starts[1:]+[len(video)])]
pngs = [(out/f'frame-{i:03}.png').read_bytes() for i in range(60)]
(out/'packets.json').write_text(json.dumps({kind:[base64.b64encode(data).decode() for data in frames]
    for kind, frames in [('png', pngs), ('h264', packets)]}))
subprocess.run([str(binary), 'measure', str(out)], check=True, timeout=120)
report = json.loads((out/'measurements.json').read_text())
report.update(dict(scope='offline Mac receiver; no Ubuntu, application session or network modified',
    width=1470, height=802, frames=60, runs=3, draw_backing_scale=2,
    source='synthetic text/controls with one animated marker; same source images for both modes',
    encoder='FFmpeg libx264 veryfast, yuv420p; not Ubuntu OpenH264',
    ffmpeg_version=subprocess.check_output([ffmpeg,'-version'],text=True).splitlines()[0],
    macos=subprocess.check_output(['sw_vers','-productVersion'],text=True).strip(),
    cpu=subprocess.check_output(['sysctl','-n','machdep.cpu.brand_string'],text=True).strip(),
    encoder_command=command,
    payloads={kind:dict(encoded_bytes=sum(map(len,frames)),
        base64_bytes=sum(len(base64.b64encode(data)) for data in frames),
        estimated_base64_MB_s_at_30fps=sum(len(base64.b64encode(data)) for data in frames)/2/1_000_000)
        for kind,frames in [('png',pngs),('h264',packets)]},
    limitations=['No actual Ubuntu encoder or network measurement', 'No real Feishu/ChatGPT visual acceptance',
                 'Processing FPS is an offline ceiling, not presented/network FPS', 'PNG does not add Retina source detail']))
(out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')
print(json.dumps(report,ensure_ascii=False,indent=2))
